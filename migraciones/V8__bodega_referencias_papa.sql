-- ---------------------------------------------------------------------------
-- DATACONTROL - bodega de papa
--
-- Nuevo rol Bodeguero, encargado de mantener las referencias de papa cruda
-- y el peso promedio de cada bulto. El operario de horno elige una
-- referencia por tanda y el peso se copia a registro_horno para conservar
-- el historico aunque bodega corrija el promedio despues.
-- ---------------------------------------------------------------------------

INSERT INTO roles (codigo, nombre) VALUES
    ('bodeguero', 'Bodeguero')
ON CONFLICT (codigo) DO NOTHING;

CREATE TABLE referencias_papa (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                   VARCHAR(120)  NOT NULL UNIQUE,
    peso_promedio_bulto_kg   NUMERIC(6, 2) NOT NULL,
    activo                   BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion           TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_referencia_papa_peso_positivo
        CHECK (peso_promedio_bulto_kg > 0)
);

COMMENT ON TABLE referencias_papa IS
    'Variedades o procedencias de papa cruda que administra Bodega.';
COMMENT ON COLUMN referencias_papa.peso_promedio_bulto_kg IS
    'Peso promedio actual de un bulto de esta referencia. Se copia al registro de horno al crear la tanda.';

ALTER TABLE registro_horno
    ADD COLUMN referencia_papa_id INTEGER NULL REFERENCES referencias_papa (id);

CREATE INDEX ix_registro_horno_referencia_papa
    ON registro_horno (referencia_papa_id);

COMMENT ON COLUMN registro_horno.referencia_papa_id IS
    'Referencia de papa usada en la tanda. NULL solo en registros historicos anteriores al catalogo.';
COMMENT ON COLUMN registro_horno.peso_estandar_bulto_kg IS
    'Copia del peso promedio de la referencia de papa al momento de crear la tanda.';
