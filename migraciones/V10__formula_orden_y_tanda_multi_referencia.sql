-- ---------------------------------------------------------------------------
-- DATACONTROL - formula de produccion por orden y tanda multi-referencia
--
-- Flujo:
--   1) El supervisor crea la orden (sin mezcla).
--   2) Bodega define la formula de ESA orden: referencias y bultos por tanda.
--   3) El operario registra cada tanda con la mezcla; una tanda puede llevar
--      varias referencias.
--
-- La formula vive en orden_referencias (no se crea otra orden). El registro
-- de horno sigue siendo la cabecera de la tanda y el detalle por referencia
-- vive en registro_horno_referencias. Los registros historicos se normalizan
-- a la tabla hija sin cambiar sus kg, bultos ni aceite.
-- ---------------------------------------------------------------------------

CREATE TABLE orden_referencias (
    id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id                  INTEGER NOT NULL REFERENCES ordenes_produccion (id) ON DELETE CASCADE,
    referencia_papa_id        INTEGER NOT NULL REFERENCES referencias_papa (id),
    bultos_por_tanda          INTEGER NOT NULL,
    bultos_planificados       INTEGER NOT NULL,
    porcentaje_produccion_pct NUMERIC(7, 4) NOT NULL,
    peso_promedio_bulto_kg    NUMERIC(6, 2) NOT NULL,
    rendimiento_fritura_pct   NUMERIC(7, 4) NOT NULL,
    kg_crudos_por_tanda       NUMERIC(10, 2) NOT NULL,
    kg_fritos_por_tanda       NUMERIC(10, 2) NOT NULL,
    kg_crudos_planificados    NUMERIC(12, 2) NOT NULL,
    kg_fritos_estimados       NUMERIC(12, 2) NOT NULL,
    creado_por_id             INTEGER NOT NULL REFERENCES usuarios (id),
    fecha_creacion            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_orden_referencia UNIQUE (orden_id, referencia_papa_id),
    CONSTRAINT ck_orden_ref_bultos_tanda CHECK (bultos_por_tanda > 0),
    CONSTRAINT ck_orden_ref_bultos_planificados CHECK (bultos_planificados > 0),
    CONSTRAINT ck_orden_ref_pct CHECK (porcentaje_produccion_pct > 0 AND porcentaje_produccion_pct <= 100),
    CONSTRAINT ck_orden_ref_peso CHECK (peso_promedio_bulto_kg > 0),
    CONSTRAINT ck_orden_ref_rendimiento CHECK (rendimiento_fritura_pct > 0 AND rendimiento_fritura_pct <= 100),
    CONSTRAINT ck_orden_ref_kg_crudos CHECK (kg_crudos_por_tanda >= 0 AND kg_crudos_planificados >= 0),
    CONSTRAINT ck_orden_ref_kg_fritos CHECK (kg_fritos_por_tanda >= 0 AND kg_fritos_estimados >= 0)
);

CREATE INDEX ix_orden_referencias_orden ON orden_referencias (orden_id);
CREATE INDEX ix_orden_referencias_referencia ON orden_referencias (referencia_papa_id);

COMMENT ON TABLE orden_referencias IS
    'Formula de produccion de una orden: bultos por referencia y por tanda, con snapshots de peso y rendimiento.';
COMMENT ON COLUMN orden_referencias.bultos_por_tanda IS
    'Bultos de esta referencia que se cargan en cada tanda. La misma mezcla se repite en todas las tandas de la orden.';
COMMENT ON COLUMN orden_referencias.bultos_planificados IS
    'bultos_por_tanda x horas_produccion. Se recalcula si el supervisor cambia las horas antes de iniciar.';

-- Marca de compatibilidad: las ordenes creadas antes de esta funcion no
-- exigen formula para producir; las nuevas si (DEFAULT TRUE).
ALTER TABLE ordenes_produccion
    ADD COLUMN formula_obligatoria BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN formula_notas TEXT NULL,
    ADD COLUMN formula_actualizada_por_id INTEGER NULL REFERENCES usuarios (id),
    ADD COLUMN formula_fecha_actualizacion TIMESTAMPTZ NULL;

COMMENT ON COLUMN ordenes_produccion.formula_obligatoria IS
    'TRUE en ordenes nuevas: Bodega debe guardar la formula antes de iniciar. FALSE en historicas.';
COMMENT ON COLUMN ordenes_produccion.formula_notas IS
    'Instrucciones opcionales de Bodega para la mezcla de la orden.';

-- Las ordenes que ya existian no tenian formula. Se marcan como historicas
-- para que sigan produciendo con el registro de horno anterior.
UPDATE ordenes_produccion SET formula_obligatoria = FALSE;

CREATE TABLE registro_horno_referencias (
    id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_horno_id         INTEGER NOT NULL REFERENCES registro_horno (id) ON DELETE CASCADE,
    referencia_papa_id        INTEGER NOT NULL REFERENCES referencias_papa (id),
    cantidad_bultos           NUMERIC(6, 2) NOT NULL,
    peso_estandar_bulto_kg    NUMERIC(6, 2) NOT NULL,
    rendimiento_fritura_pct   NUMERIC(7, 4) NULL,
    porcentaje_produccion_pct NUMERIC(7, 4) NULL,
    kg_crudos_calculados      NUMERIC(10, 2) NOT NULL,
    kg_fritos_estimados       NUMERIC(12, 2) NULL,
    CONSTRAINT uq_registro_ref UNIQUE (registro_horno_id, referencia_papa_id),
    CONSTRAINT ck_registro_ref_bultos CHECK (cantidad_bultos > 0),
    CONSTRAINT ck_registro_ref_peso CHECK (peso_estandar_bulto_kg > 0),
    CONSTRAINT ck_registro_ref_rendimiento CHECK (
        rendimiento_fritura_pct IS NULL
        OR (rendimiento_fritura_pct > 0 AND rendimiento_fritura_pct <= 100)
    ),
    CONSTRAINT ck_registro_ref_participacion CHECK (
        porcentaje_produccion_pct IS NULL
        OR (porcentaje_produccion_pct >= 0 AND porcentaje_produccion_pct <= 100)
    ),
    CONSTRAINT ck_registro_ref_kg_crudos CHECK (kg_crudos_calculados >= 0),
    CONSTRAINT ck_registro_ref_kg_fritos CHECK (
        kg_fritos_estimados IS NULL OR kg_fritos_estimados >= 0
    )
);

CREATE INDEX ix_registro_ref_registro ON registro_horno_referencias (registro_horno_id);
CREATE INDEX ix_registro_ref_referencia ON registro_horno_referencias (referencia_papa_id);

COMMENT ON TABLE registro_horno_referencias IS
    'Detalle por referencia de una tanda. La cabecera registro_horno guarda la suma de bultos y kg.';
COMMENT ON COLUMN registro_horno_referencias.peso_estandar_bulto_kg IS
    'Peso congelado al crear la tanda. Un cambio posterior en Bodega no altera el historico.';

-- La columna vieja queda solo para registros historicos: las tandas nuevas
-- usan la tabla hija. La cabecera conserva la suma de bultos y kg.
ALTER TABLE registro_horno ALTER COLUMN referencia_papa_id DROP NOT NULL;
ALTER TABLE registro_horno ALTER COLUMN peso_estandar_bulto_kg DROP NOT NULL;

-- Backfill: cada registro historico con una referencia genera su fila hija
-- con los mismos valores congelados. No se toca ningun kg del historico.
INSERT INTO registro_horno_referencias (
    registro_horno_id, referencia_papa_id, cantidad_bultos,
    peso_estandar_bulto_kg, rendimiento_fritura_pct, porcentaje_produccion_pct,
    kg_crudos_calculados, kg_fritos_estimados
)
SELECT id, referencia_papa_id, cantidad_bultos,
       peso_estandar_bulto_kg, rendimiento_fritura_pct, porcentaje_produccion_pct,
       kg_crudos_calculados, kg_fritos_estimados
FROM registro_horno
WHERE referencia_papa_id IS NOT NULL
  AND peso_estandar_bulto_kg IS NOT NULL
  AND kg_crudos_calculados IS NOT NULL;
