-- ---------------------------------------------------------------------------
-- DATACONTROL - formula de la noche por horno
--
-- La bodeguera trabaja de dia. Antes de irse deja, por cada horno, la mezcla
-- de papa que dejo despachada (referencias y bultos por tanda). Una orden
-- que se crea en ese horno sin formula del producto toma esa mezcla sola y
-- queda marcada como automatica; al dia siguiente Bodega la confirma o la
-- corrige. La formula activa del producto sigue teniendo prioridad.
-- ---------------------------------------------------------------------------

CREATE TABLE formula_noche_horno (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horno_id             INTEGER NOT NULL REFERENCES hornos (id),
    referencia_papa_id   INTEGER NOT NULL REFERENCES referencias_papa (id),
    bultos_por_tanda     INTEGER NOT NULL CONSTRAINT ck_formula_noche_bultos CHECK (bultos_por_tanda > 0),
    actualizado_por_id   INTEGER NULL REFERENCES usuarios (id),
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_formula_noche_horno UNIQUE (horno_id, referencia_papa_id)
);

-- La formula de la orden la puso la app (la de la noche) y Bodega la debe
-- confirmar.
ALTER TABLE ordenes_produccion
    ADD COLUMN formula_automatica BOOLEAN NOT NULL DEFAULT FALSE;

-- Recordatorio diario a Bodega para dejar la formula de la noche.
ALTER TABLE notificaciones DROP CONSTRAINT IF EXISTS ck_notificacion_tipo_valido;
ALTER TABLE notificaciones ADD CONSTRAINT ck_notificacion_tipo_valido
    CHECK (tipo IN (
        'orden_creada',
        'produccion_por_terminar',
        'orden_para_bodega',
        'formula_lista',
        'produccion_terminada',
        'orden_cerrada_sola',
        'recordar_formula_noche'
    ));
