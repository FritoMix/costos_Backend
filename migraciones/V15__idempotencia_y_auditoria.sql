CREATE TABLE operaciones_idempotentes (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
    ambito VARCHAR(200) NOT NULL,
    clave VARCHAR(128) NOT NULL,
    solicitud_hash VARCHAR(64) NOT NULL,
    respuesta JSONB,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, ambito, clave)
);
CREATE INDEX ix_idempotencia_creada ON operaciones_idempotentes(creada_en);

CREATE TABLE auditoria_operaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurso VARCHAR(40) NOT NULL,
    recurso_id INTEGER NOT NULL,
    usuario_id INTEGER REFERENCES usuarios(id),
    accion VARCHAR(50) NOT NULL,
    antes JSONB,
    despues JSONB,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_auditoria_recurso ON auditoria_operaciones(recurso, recurso_id, fecha);
