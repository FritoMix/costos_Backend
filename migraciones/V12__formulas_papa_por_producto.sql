-- ---------------------------------------------------------------------------
-- DATACONTROL - formulas de papa reutilizables por producto
--
-- Flujo nuevo:
--   1) Bodega crea una formula para un producto (referencias y bultos por
--      tanda) y la ACTIVA. Solo puede haber una activa por producto.
--   2) Al crear una orden, el supervisor ve la formula activa en solo lectura
--      y la orden nace con esa mezcla copiada (orden_referencias), igual que
--      si Bodega la hubiera guardado a mano.
--   3) Si el producto no tiene formula activa, o la activa no cabe en el
--      horno elegido, la orden queda pendiente y Bodega la define como hoy.
--
-- La formula de la orden sigue siendo la copia congelada en
-- orden_referencias; estas tablas son el catalogo reutilizable.
-- ---------------------------------------------------------------------------

CREATE TABLE formulas_papa (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  VARCHAR(150) NOT NULL,
    producto_id             INTEGER NOT NULL REFERENCES productos (id),
    activa                  BOOLEAN NOT NULL DEFAULT FALSE,
    notas                   TEXT NULL,
    creado_por_id           INTEGER NOT NULL REFERENCES usuarios (id),
    fecha_creacion          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_formula_papa_nombre_producto UNIQUE (producto_id, nombre)
);

-- Una sola formula activa por producto. El indice parcial lo garantiza en la
-- base: al activar otra, el servicio desactiva la anterior primero.
CREATE UNIQUE INDEX ux_formula_papa_activa_por_producto
    ON formulas_papa (producto_id)
    WHERE activa;

COMMENT ON TABLE formulas_papa IS
    'Catalogo de formulas reutilizables de Bodega. La activa de cada producto se aplica a las ordenes nuevas.';
COMMENT ON COLUMN formulas_papa.activa IS
    'TRUE en la formula vigente del producto. Solo puede haber una por producto (indice unico parcial).';

CREATE TABLE formula_papa_referencias (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formula_papa_id         INTEGER NOT NULL REFERENCES formulas_papa (id) ON DELETE CASCADE,
    referencia_papa_id      INTEGER NOT NULL REFERENCES referencias_papa (id),
    bultos_por_tanda        INTEGER NOT NULL,
    CONSTRAINT uq_formula_papa_referencia UNIQUE (formula_papa_id, referencia_papa_id),
    CONSTRAINT ck_formula_papa_ref_bultos CHECK (bultos_por_tanda > 0)
);

CREATE INDEX ix_formula_papa_ref_referencia
    ON formula_papa_referencias (referencia_papa_id);

COMMENT ON TABLE formula_papa_referencias IS
    'Mezcla de una formula reutilizable: bultos de cada referencia en cada tanda.';

-- Trazabilidad: de que formula activa salio la mezcla de la orden (NULL en
-- ordenes historicas o cuando Bodega la definio a mano).
ALTER TABLE ordenes_produccion
    ADD COLUMN formula_papa_id INTEGER NULL REFERENCES formulas_papa (id) ON DELETE SET NULL;

COMMENT ON COLUMN ordenes_produccion.formula_papa_id IS
    'Formula reutilizable que origino la mezcla de la orden. NULL si Bodega la definio a mano.';
