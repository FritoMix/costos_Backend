-- ---------------------------------------------------------------------------
-- DATACONTROL - lineas de produccion, variedades, unidad de la orden por
-- linea, rango de % de sabor y recuperar la contraseña sin correo.
--
-- Todo lo que ya existe queda como linea PAPA y sigue igual: mismos hornos,
-- mismas formulas de Bodega, misma unidad (kg o canastillas), mismos bultos.
--
-- * lineas: papa, platano, pellet, extruido (chitos), trocillo y nachos.
--   Cada horno pertenece a una; la linea de la orden es la de su horno.
--   Solo la papa usa Bodega (formula y referencias de papa).
-- * Cada linea pide la orden en su unidad:
--     papa      kg o canastillas      platano   kg fritos
--     nachos    kg o canastillas      trocillo  mojes
--     extruido  baches                pellet    bultos crudos
--   En mojes, baches y bultos la orden guarda cuantos se pidieron y la meta
--   en kg queda en 0: la app captura lo real, no estima.
-- * Las lineas que no son papa registran en el horno los kg de materia prima
--   (no bultos de papa).
-- * Operarios y Bodega pertenecen a una linea y solo ven la suya.
--   Administrador y supervisor no tienen linea: ven todas.
-- * Variedad de la materia prima en la orden (platano: Harton, FHIA 21).
-- * Rango de % de sabor esperado por producto (control, no calculo).
-- * Recuperar la contraseña: aviso al administrador y a los supervisores,
--   contraseña temporal y obligacion de crear una nueva al entrar.
-- ---------------------------------------------------------------------------

CREATE TABLE lineas (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                 VARCHAR(20)  NOT NULL UNIQUE,
    nombre                 VARCHAR(60)  NOT NULL,
    unidad_materia_prima   VARCHAR(10)  NOT NULL DEFAULT 'kg'
        CONSTRAINT ck_linea_unidad CHECK (unidad_materia_prima IN ('bultos', 'kg')),
    nombre_materia_prima   VARCHAR(40)  NOT NULL,
    usa_bodega             BOOLEAN      NOT NULL DEFAULT FALSE,
    pide_variedad          BOOLEAN      NOT NULL DEFAULT FALSE,
    unidades_orden         VARCHAR(80)  NOT NULL DEFAULT 'kg',
    orden                  SMALLINT     NOT NULL DEFAULT 0,
    activo                 BOOLEAN      NOT NULL DEFAULT TRUE
);

INSERT INTO lineas (codigo, nombre, unidad_materia_prima, nombre_materia_prima,
                    usa_bodega, pide_variedad, unidades_orden, orden) VALUES
    ('papa',     'Papa',                      'bultos', 'papa',     TRUE,  FALSE, 'kg,canastillas', 1),
    ('platano',  'Plátano',                   'kg',     'plátano',  FALSE, TRUE,  'kg',             2),
    ('pellet',   'Pellet',                    'kg',     'pellet',   FALSE, FALSE, 'bultos',         3),
    ('extruido', 'Extruido de maíz (chitos)', 'kg',     'maíz',     FALSE, FALSE, 'baches',         4),
    ('trocillo', 'Trocillo',                  'kg',     'trocillo', FALSE, FALSE, 'mojes',          5),
    ('nachos',   'Nachos',                    'kg',     'nacho',    FALSE, FALSE, 'kg,canastillas', 6);

-- Todos los hornos que ya existen son de papa.
ALTER TABLE hornos ADD COLUMN linea_id INTEGER NULL REFERENCES lineas (id);
UPDATE hornos SET linea_id = (SELECT id FROM lineas WHERE codigo = 'papa');
ALTER TABLE hornos ALTER COLUMN linea_id SET NOT NULL;

-- Los operarios y la bodega que ya existen son de papa.
ALTER TABLE usuarios ADD COLUMN linea_id INTEGER NULL REFERENCES lineas (id);
UPDATE usuarios SET linea_id = (SELECT id FROM lineas WHERE codigo = 'papa')
WHERE rol_id IN (SELECT id FROM roles
                 WHERE codigo IN ('operario_horno', 'operario_saborizado', 'bodeguero'));

-- Recuperar la contraseña: entro con una temporal y debe crear la suya.
ALTER TABLE usuarios ADD COLUMN debe_cambiar_password BOOLEAN NOT NULL DEFAULT FALSE;

-- Variedades de la materia prima por linea.
CREATE TABLE variedades (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    linea_id  INTEGER     NOT NULL REFERENCES lineas (id),
    nombre    VARCHAR(80) NOT NULL,
    activo    BOOLEAN     NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX ux_variedad_nombre ON variedades (linea_id, lower(nombre));

INSERT INTO variedades (linea_id, nombre)
SELECT id, v.nombre FROM lineas, (VALUES ('Hartón'), ('FHIA 21')) AS v (nombre)
WHERE codigo = 'platano';

ALTER TABLE ordenes_produccion ADD COLUMN variedad_id INTEGER NULL REFERENCES variedades (id);

-- Unidades de la orden por linea.
ALTER TABLE ordenes_produccion DROP CONSTRAINT ck_orden_unidad_solicitada_valida;
ALTER TABLE ordenes_produccion ADD CONSTRAINT ck_orden_unidad_solicitada_valida
    CHECK (unidad_solicitada IN ('kg', 'canastillas', 'mojes', 'baches', 'bultos'));

-- La meta en kg sigue siendo positiva, salvo en las ordenes pedidas en
-- mojes, baches o bultos: ahi va en 0 y lo pedido queda en
-- cantidad_canastillas_solicitadas (cuantos se pidieron). NOT VALID, como en
-- V16: protege escrituras nuevas sin revisar historicos.
ALTER TABLE ordenes_produccion DROP CONSTRAINT ck_orden_cantidad_positiva;
ALTER TABLE ordenes_produccion ADD CONSTRAINT ck_orden_cantidad_positiva
    CHECK (
        cantidad_programada <> 'NaN'::numeric
        AND (
            cantidad_programada > 0
            OR (
                unidad_solicitada IN ('mojes', 'baches', 'bultos')
                AND cantidad_programada = 0
                AND cantidad_canastillas_solicitadas > 0
            )
        )
    ) NOT VALID;

-- Las tandas de papa llevan bultos; las de las demas lineas llevan 0 bultos
-- y los kg de materia prima que entraron.
ALTER TABLE registro_horno DROP CONSTRAINT ck_horno_bultos_positivos;
ALTER TABLE registro_horno ADD CONSTRAINT ck_horno_bultos_positivos
    CHECK (
        cantidad_bultos <> 'NaN'::numeric
        AND (cantidad_bultos > 0 OR (cantidad_bultos = 0 AND kg_crudos_calculados > 0))
    ) NOT VALID;

-- Rango de % de sabor esperado por producto.
ALTER TABLE productos ADD COLUMN sabor_minimo_pct NUMERIC(5, 2) NULL
    CONSTRAINT ck_producto_sabor_minimo CHECK (sabor_minimo_pct >= 0 AND sabor_minimo_pct <= 100);
ALTER TABLE productos ADD COLUMN sabor_maximo_pct NUMERIC(5, 2) NULL
    CONSTRAINT ck_producto_sabor_maximo CHECK (sabor_maximo_pct > 0 AND sabor_maximo_pct <= 100);
ALTER TABLE productos ADD CONSTRAINT ck_producto_rango_sabor
    CHECK (sabor_minimo_pct IS NULL OR sabor_maximo_pct IS NULL OR sabor_minimo_pct <= sabor_maximo_pct);

-- Aviso de "olvide mi contraseña".
ALTER TABLE notificaciones DROP CONSTRAINT IF EXISTS ck_notificacion_tipo_valido;
ALTER TABLE notificaciones ADD CONSTRAINT ck_notificacion_tipo_valido
    CHECK (tipo IN (
        'orden_creada',
        'produccion_por_terminar',
        'orden_para_bodega',
        'formula_lista',
        'produccion_terminada',
        'orden_cerrada_sola',
        'recordar_formula_noche',
        'recuperar_password'
    ));
