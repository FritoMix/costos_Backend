-- ---------------------------------------------------------------------------
-- DATACONTROL - aceite agregado en la tanda y catalogo de tipos de aceite
--
-- * aceite_agregado_litros: litros que se agregaron al tanque durante la
--   tanda (reposicion). Se suman al consumo medido por nivel, asi que el
--   nivel final puede quedar por encima del inicial sin dar un consumo
--   negativo. Los registros existentes quedan en 0 (sin cambio).
-- * tipos_aceite: aceites de fritura con densidad fija (kg/L) y proveedor.
--   Un horno puede tener su aceite; la densidad del catalogo solo se usa
--   cuando ese horno no tiene ninguna muestra de densidad (las muestras
--   siguen mandando, como hasta ahora).
-- ---------------------------------------------------------------------------

ALTER TABLE registro_horno
    ADD COLUMN aceite_agregado_litros NUMERIC(10, 2) NOT NULL DEFAULT 0
        CONSTRAINT ck_registro_horno_aceite_agregado_no_negativo CHECK (aceite_agregado_litros >= 0);

CREATE TABLE tipos_aceite (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                 VARCHAR(100)  NOT NULL UNIQUE,
    densidad_kg_por_litro  NUMERIC(6, 4) NOT NULL,
    proveedor              VARCHAR(150)  NULL,
    activo                 BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_tipo_aceite_densidad CHECK (densidad_kg_por_litro > 0.5 AND densidad_kg_por_litro < 1.2)
);

ALTER TABLE hornos ADD COLUMN aceite_id INTEGER NULL REFERENCES tipos_aceite (id);
ALTER TABLE registro_horno ADD COLUMN aceite_id INTEGER NULL REFERENCES tipos_aceite (id);
